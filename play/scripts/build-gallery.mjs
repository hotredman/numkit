// Build-time gallery index: scans play/gallery/*.m for %{ @play ... %}
// manifests, emits play/src/gallery.generated.js with titles + raw
// sources. The engine-side extractor (play_manifest.cpp) defines the
// format; this mirrors the SAME rules for the web side (canonical
// @play marker, legacy %{#ui alias, first manifest wins).
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const galleryDir = path.resolve(here, '../gallery');
const outFile = path.resolve(here, '../src/gallery.generated.ts');

function extractManifest(source) {
  // Mirrors nk::extractPlayManifest (see src/core/src/play_manifest.cpp).
  const pos = source.indexOf('%{');
  if (pos < 0) return '';
  // Block-comment opener must sit at a line start.
  if (pos > 0 && !/[\s]/.test(source[pos - 1])) return '';
  let i = pos + 2;
  while (i < source.length && /\s/.test(source[i])) i++;
  let markerLen = 0;
  if (source.startsWith('@play', i) && !/\S/.test(source[i + 5] ?? '')) markerLen = 5;
  else if (source.startsWith('#ui', i) && !/\S/.test(source[i + 3] ?? '')) markerLen = 3;
  if (!markerLen) return '';
  i += markerLen;
  const close = source.indexOf('%}', i);
  if (close < 0) return '';
  return source.slice(i, close).trim();
}

const files = (await readdir(galleryDir, { recursive: true }).catch(() => [])).filter((f) => f.endsWith('.m'));
const entries = [];
for (const f of files.sort()) {
  const source = await readFile(path.join(galleryDir, f), 'utf-8');
  const raw = extractManifest(source);
  let title = f.replace(/\.m$/, '');
  let description = '';
  if (raw) {
    try {
      const m = JSON.parse(raw);
      title = m.title ?? title;
      description = m.description ?? '';
    } catch { /* malformed manifest: keep filename */ }
  }
  entries.push({ id: f.split(path.sep).join('/'), title, description, source });
}

const body = `// AUTO-GENERATED by play/scripts/build-gallery.mjs — do not edit.
import type { GalleryEntry } from './lib/galleryTypes.js';

export const gallery: GalleryEntry[] = ${JSON.stringify(entries, null, 2)};
`;
await writeFile(outFile, body, 'utf-8');
console.log(`gallery: ${entries.length} entr${entries.length === 1 ? 'y' : 'ies'} -> src/gallery.generated.ts`);
