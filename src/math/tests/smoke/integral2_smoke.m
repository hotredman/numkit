% Multi-dimensional numerical integration via nested adaptive 1-D integral.
% bugs/builtin/numerical-integration-nd.

fprintf('integral2 x*y over [0,1]^2 = %.12f  (expect 0.25)\n', ...
        integral2(@(x,y) x.*y, 0, 1, 0, 1));
fprintf('integral2 exp(x*y)        = %.12f  (expect 1.317902151454)\n', ...
        integral2(@(x,y) exp(x.*y), 0, 1, 0, 1));
fprintf('integral3 x+y+z over [0,1]^3 = %.12f  (expect 1.5)\n', ...
        integral3(@(x,y,z) x+y+z, 0,1,0,1,0,1));
fprintf('quadgk exp(-x^2) over [0,1]  = %.15f  (expect 0.746824132812427)\n', ...
        quadgk(@(x) exp(-x.^2), 0, 1));
fprintf('quad2d x*y over [0,1]^2      = %.12f  (expect 0.25)\n', ...
        quad2d(@(x,y) x.*y, 0, 1, 0, 1));
